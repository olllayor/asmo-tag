import { writeFileSync } from "node:fs";
import { migrationStatements, schemaVersion } from "../src/store/schema.js";

// Keeps migrations/0001-edge-schema.sql in step with src/store/schema.ts. The Node path
// applies the array inside one transaction guarded by PRAGMA user_version; the edge path
// goes through wrangler d1 execute, which has no such guard, so the SQL here is written to
// be re-runnable: every object is created with IF NOT EXISTS and the version row is an
// upsert. Without that, a second `pnpm db:migrate` against an already-migrated database
// fails on "table workspaces already exists".
const sql = [
  "-- Edge schema for Cloudflare D1, applied by wrangler d1 execute",
  "-- (ASMO_D1_COMMAND set, then pnpm db:migrate). Generated by scripts/sync-edge-migration.ts.",
  "-- Safe to re-run: every statement is idempotent.",
  "",
  "CREATE TABLE IF NOT EXISTS asmo_schema_meta(name TEXT PRIMARY KEY NOT NULL, version INTEGER NOT NULL);",
  ...migrationStatements.map(statement => statement.trim().replace(/;$/, "").replace(/^CREATE TABLE\b/i, "CREATE TABLE IF NOT EXISTS").replace(/^CREATE INDEX\b/i, "CREATE INDEX IF NOT EXISTS") + ";"),
  `INSERT INTO asmo_schema_meta(name,version) VALUES('schema',${schemaVersion}) ON CONFLICT(name) DO UPDATE SET version=${schemaVersion};`,
  "",
].join("\n");

writeFileSync("migrations/0001-edge-schema.sql", sql);
console.log(`migrations/0001-edge-schema.sql: ${sql.length} bytes, ${migrationStatements.length} statements, schema v${schemaVersion}`);
